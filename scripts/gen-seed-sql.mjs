/**
 * Generates supabase/seed.sql from the TypeScript seed, so the
 * local adapter and the database serve the same catalogue and cannot drift.
 *
 *   node scripts/gen-seed-sql.mjs <compiled-dir> [--reference <migration.sql>]
 *
 * --reference also writes the reference data alone (localities, deal types,
 * categories) as a migration, because production needs those rows and
 * seed.sql never runs there. Write a new migration whenever they change;
 * never rewrite one that has been pushed.
 *
 * Expects the seed modules compiled to CommonJS first; npm run gen:seed does
 * both steps. Slug ids in TypeScript ('biz-rangoli', 'd-001') become stable
 * UUIDs here via an md5-derived v5-shaped uuid, so a row keeps the same id
 * across regenerations and the two worlds stay comparable.
 */

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { argv, cwd } from 'node:process';

// require() resolves a relative specifier against this file's directory, not
// the working directory, so the argument is made absolute up front.
const outDir = argv[2] ? resolve(cwd(), argv[2]) : undefined;
const refAt = argv.indexOf('--reference');
const referenceOut = refAt > 0 && argv[refAt + 1] ? resolve(cwd(), argv[refAt + 1]) : undefined;
if (!outDir) {
  console.error('usage: node scripts/gen-seed-sql.mjs <compiled-dir>');
  process.exit(2);
}

const require_ = createRequire(import.meta.url);

// tsc flattens the output when every input shares a directory, so the compiled
// files may sit at the root or under data/ depending on what was compiled.
function load(name) {
  for (const candidate of [`${outDir}/${name}.js`, `${outDir}/data/${name}.js`]) {
    try {
      return require_(candidate);
    } catch (e) {
      if (e.code !== 'MODULE_NOT_FOUND') throw e;
    }
  }
  throw new Error(`cannot find compiled ${name}.js under ${outDir}`);
}

const ref = load('seed-reference');
const deals = load('seed-deals');

const { LOCALITIES, CATEGORIES, BUSINESSES, DEMO_BUSINESS_ID } = ref;
const { SEED_DEALS, SEED_PIPELINE_DEALS, SEED_ADMIN_QUEUE_DEALS } = deals;

/** Deterministic uuid from a slug, shaped like a v5. */
function uu(slug) {
  const h = createHash('md5').update(slug).digest('hex');
  return [
    h.slice(0, 8),
    h.slice(8, 12),
    '5' + h.slice(13, 16),
    ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16) + h.slice(17, 20),
    h.slice(20, 32),
  ].join('-');
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === '' ? 'null' : String(v));
const b = (v) => (v ? 'true' : 'false');
const pt = (loc) => `st_setsrid(st_makepoint(${loc.lng}, ${loc.lat}), 4326)::geography`;
const arr = (xs) =>
  xs && xs.length ? `array[${xs.map((x) => q(x)).join(',')}]::text[]` : `'{}'::text[]`;

