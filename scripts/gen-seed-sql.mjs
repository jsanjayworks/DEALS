// ---- reference data: localities, deal types, categories ----
function referenceSql(w) {
w('-- ------------------------------------------------------ localities --------');
for (const l of LOCALITIES) {
  w(`insert into localities (id, name, city, centroid, aliases)
  values (${q(uu(l.id))}, ${q(l.name)}, ${q(l.city)}, ${pt(l.centroid)}, ${arr(l.aliases)})
  on conflict (name, city) do update set centroid = excluded.centroid, aliases = excluded.aliases;`);
}
w();

// ---- deal types ----
w('-- ------------------------------------------------------ deal types --------');
for (const [code, name] of DEAL_TYPES) {
  w(`insert into deal_types (code, name) values (${q(code)}, ${q(name)})
  on conflict (code) do update set name = excluded.name;`);
}
w();

// ---- categories: parents first, so the self-FK resolves ----
w('-- ------------------------------------------------------ categories --------');
const ordered = [
  ...CATEGORIES.filter((c) => c.parent_id === null),
  ...CATEGORIES.filter((c) => c.parent_id !== null),
];
let sort = 0;
for (const c of ordered) {
  w(`insert into categories (id, parent_id, slug, name, vertical, icon, attribute_schema, sort_order)
  values (${q(uu(c.id))}, ${c.parent_id ? q(uu(c.parent_id)) : 'null'}, ${q(c.slug)}, ${q(c.name)}, ${q(c.vertical)}, ${q(c.icon)}, ${q(JSON.stringify(c.attribute_schema ?? {}))}::jsonb, ${sort++})
  on conflict (slug) do update set name = excluded.name, icon = excluded.icon, parent_id = excluded.parent_id,
    vertical = excluded.vertical, attribute_schema = excluded.attribute_schema;`);
}
w();
}
referenceSql(w);

// ---- businesses, their locations, and the demo membership ----
w('-- ------------------------------------------------------ businesses --------');
for (const biz of BUSINESSES) {
  w(`insert into businesses (id, name, phone, email, primary_category_id, verification_status, rating_avg, rating_count)
  values (${q(uu(biz.id))}, ${q(biz.name)}, ${q(biz.phone)}, ${q(biz.email)}, ${q(uu(biz.primary_category_id))}, ${q(biz.verification_status)}, ${n(biz.rating_avg)}, ${n(biz.rating_count)})
  on conflict (id) do update set name = excluded.name, verification_status = excluded.verification_status;`);
  w(`insert into business_locations (id, business_id, address_line, locality_id, city, location, is_primary)
  values (${q(uu(biz.id + '-loc'))}, ${q(uu(biz.id))}, ${q(biz.address_line)}, ${q(uu(biz.locality_id))}, 'Bengaluru', ${pt(biz.location)}, true)
  on conflict (id) do update set location = excluded.location, address_line = excluded.address_line;`);
}
w();
w('-- The demo merchant owns one business, which is what unlocks merchant mode.');
w(`insert into business_members (business_id, profile_id, member_role)
  values (${q(uu(DEMO_BUSINESS_ID))}, ${q(uu('usr-demo-merchant'))}, 'owner')
  on conflict (business_id, profile_id) do nothing;`);
w();

// ---- deals ----
const ALL = [...SEED_DEALS, ...SEED_PIPELINE_DEALS, ...SEED_ADMIN_QUEUE_DEALS];
w('-- ----------------------------------------------------------- deals --------');
w(`-- ${SEED_DEALS.length} live, ${SEED_PIPELINE_DEALS.length} in the merchant pipeline,`);
w(`-- ${SEED_ADMIN_QUEUE_DEALS.length} awaiting admin review. Dates are relative to`);
w('-- the moment this file was generated, so the Today and Ending Soon rails have');
w('-- content; regenerate if they go stale.');
w();

for (const d of ALL) {
  const id = uu(d.id);
  // capacity_remaining and status are revoked from clients but writable by the
  // owner running this file, so the seed can land mid-lifecycle deals.
  w(`insert into deals (
  id, business_id, category_id, deal_type_code, offering_kind, title,
  short_description, description, status, original_price, deal_price,
  price_unit, taxes_note, min_purchase, max_qty_per_customer, starts_at, ends_at,
  capacity_total, capacity_remaining, booking_required, cancellation_policy,
  terms, attributes, tags, location, search_radius_m, rejection_reason,
  published_at, rating_avg, rating_count, view_count, search_count
) values (
  ${q(id)}, ${q(uu(d.business_id))}, ${q(uu(d.category_id))}, ${q(d.deal_type_code)}, ${q(d.offering_kind)}, ${q(d.title)},
  ${q(d.short_description)}, ${q(d.description)}, ${q(d.status)}, ${n(d.original_price)}, ${n(d.deal_price)},
  ${q(d.price_unit)}, ${q(d.taxes_note)}, ${n(d.min_purchase)}, ${n(d.max_qty_per_customer)}, ${q(d.starts_at)}, ${q(d.ends_at)},
  ${n(d.capacity_total)}, ${n(d.capacity_remaining)}, ${b(d.booking_required)}, ${q(d.cancellation_policy)},
  ${q(d.terms)}, ${q(JSON.stringify(d.attributes))}::jsonb, ${arr(d.tags)}, ${pt(d.location)}, 5000, ${q(d.rejection_reason)},
  ${q(d.published_at)}, ${n(d.rating_avg)}, ${n(d.rating_count)}, ${n(d.views)}, ${n(d.searches)}
) on conflict (id) do update set
  title = excluded.title, status = excluded.status, ends_at = excluded.ends_at,
  capacity_remaining = excluded.capacity_remaining, published_at = excluded.published_at,
  attributes = excluded.attributes, tags = excluded.tags;`);

  w(`insert into deal_media (id, deal_id, kind, storage_path, position)
  values (${q(uu(d.id + '-img'))}, ${q(id)}, 'image', ${q(d.image)}, 0)
  on conflict (id) do update set storage_path = excluded.storage_path;`);

  w(`delete from deal_availability where deal_id = ${q(id)};`);
  const days = d.availability.days;
  if (days.length === 0) {
    w(`insert into deal_availability (deal_id, day_of_week, start_time, end_time)
  values (${q(id)}, null, ${q(d.availability.start_time)}, ${q(d.availability.end_time)});`);
  } else {
    const rows = days
      .map((dw) => `(${q(id)}, ${dw}, ${q(d.availability.start_time)}, ${q(d.availability.end_time)})`)
      .join(',\n         ');
    w(`insert into deal_availability (deal_id, day_of_week, start_time, end_time)
  values ${rows};`);
  }

  const e = d.eligibility;
  w(`insert into deal_eligibility (deal_id, audience, min_age, min_spend, membership_required, advance_booking_hours, custom_rule)
  values (${q(id)}, ${q(e.audience)}, ${n(e.min_age)}, ${n(e.min_spend)}, ${b(e.membership_required)}, ${n(e.advance_booking_hours)}, ${q(e.custom_rule)})
  on conflict (deal_id) do update set min_age = excluded.min_age, audience = excluded.audience;`);

  w(`delete from deal_actions where deal_id = ${q(id)};`);
  const ctas = [
    `(${q(id)}, ${q(d.primary_cta)}, true, 0)`,
    ...d.secondary_ctas
      .filter((c) => c !== d.primary_cta)
      .map((c, i) => `(${q(id)}, ${q(c)}, false, ${i + 1})`),
  ].join(',\n         ');
  w(`insert into deal_actions (deal_id, action_type, is_primary, sort_order)
  values ${ctas};`);

  w(`insert into deal_locations (deal_id, business_location_id, mode, location, service_radius_m)
  values (${q(id)}, ${q(uu(d.business_id + '-loc'))}, 'store', ${pt(d.location)}, 5000)
  on conflict (deal_id, business_location_id) do nothing;`);
  w();
}

// ---- tags table, from the denormalized arrays ----
w('-- ------------------------------------------------------------- tags -------');
const tagSet = new Set(ALL.flatMap((d) => d.tags));
for (const t of [...tagSet].sort()) {
  w(`insert into tags (id, slug) values (${q(uu('tag-' + t))}, ${q(t)}) on conflict (slug) do nothing;`);
}
w();

w('-- Rolls the seeded view counts into the daily table the merchant analytics');
w('-- screen reads, so the dashboard is not empty before any real traffic.');
w(`insert into deal_analytics_daily (deal_id, day, impressions, views, search_appearances)
select id, current_date, view_count * 3, view_count, search_count from deals
on conflict (deal_id, day) do update set
  impressions = excluded.impressions, views = excluded.views,
  search_appearances = excluded.search_appearances;`);
w();

const sql = out.join('\n') + '\n';
writeFileSync('supabase/seed.sql', sql);

