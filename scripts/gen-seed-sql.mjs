const out = [];
const w = (s = '') => out.push(s);

w('-- ============================================================================');
w('-- YOLO Deals — seed: demo catalogue');
w('--');
w('-- GENERATED by scripts/gen-seed-sql.mjs from src/data/seed-*.ts.');
w('-- Do not edit by hand: regenerate with `npm run gen:seed`.');
w('--');
w('-- Idempotent. Safe to re-run; rows are upserted on their natural keys.');
w('-- ============================================================================');
w();
w('-- Seeded rows are inserted as the table owner, so RLS is bypassed here by');
w('-- design. Nothing in this file depends on a signed-in user.');
w();
w('-- LOCAL ONLY. This file makes demo accounts (one of them an admin) and sample');
w('-- businesses. It refuses to run unless the session says it is a local database,');
w('-- so `supabase db push --include-seed` or `db reset --linked` cannot put it in');
w('-- production. scripts/db-reset.sh sets this; locally you can run it by hand with');
w("--   set app.allow_seed = 'on';");
w('do $$');
w('begin');
w("  if current_setting('app.allow_seed', true) is distinct from 'on' then");
w("    raise exception 'seed.sql is for local databases only (set app.allow_seed = on to run it)';");
w('  end if;');
w('  -- Never on a database marked as production, or one people already use.');
w("  if to_regclass('public.app_settings') is not null");
w("     and exists (select 1 from public.app_settings where key = 'environment' and value = 'production') then");
w("    raise exception 'seed.sql refuses to run: this database is marked as production';");
w('  end if;');
w("  if exists (select 1 from auth.users) then");
w("    raise exception 'seed.sql refuses to run: this database already has accounts';");
w('  end if;');
w('end $$;');
w();

// ---- auth users and profiles ----
w('-- ------------------------------------------------- demo accounts ----------');
w('-- Apple and Google reviewers sign in as the customer; the same phone with a');
w('-- fixed OTP reaches merchant mode because of the business_members row below.');
w('-- Complete rows, the way Supabase Auth writes them: it ignores a user without');
w('-- aud, role and instance_id, and fails reading NULL token columns. Each login');
w('-- also needs an email identity. Auth stores phones without the leading +.');
for (const u of USERS) {
  const id = q(uu(u.slug));
  w(`insert into auth.users (instance_id, id, aud, role, email, phone, email_confirmed_at, phone_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change, email_change_token_new,
    email_change_token_current, phone_change, phone_change_token, reauthentication_token)
  values ('00000000-0000-0000-0000-000000000000', ${id}, 'authenticated', 'authenticated',
    ${q(u.email)}, ${q(u.phone.replace(/^\+/, ''))}, now(), now(),
    '{"provider":"email","providers":["email","phone"]}', '{}', now(), now(),
    '', '', '', '', '', '', '', '')
  on conflict (id) do nothing;`);
  w(`insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (${id}, ${id}, jsonb_build_object('sub', ${id}, 'email', ${q(u.email)}, 'email_verified', true),
    'email', now(), now(), now())
  on conflict (provider_id, provider) do nothing;`);
}
w();
for (const u of USERS) {
  w(`insert into profiles (id, is_admin, full_name, phone, email, date_of_birth, is_yolo_verified, onboarded_at)
  values (${q(uu(u.slug))}, ${b(u.admin)}, ${q(u.name)}, ${q(u.phone)}, ${q(u.email)}, ${q(u.dob)}, ${b(u.verified)}, now())
  on conflict (id) do update set full_name = excluded.full_name, is_admin = excluded.is_admin,
    phone = excluded.phone, email = excluded.email, date_of_birth = excluded.date_of_birth,
    is_yolo_verified = excluded.is_yolo_verified, onboarded_at = excluded.onboarded_at;`);
}
